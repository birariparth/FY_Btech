student = ("Alice", 20, "CS", 9.1, "Pune")
# Display all elements
print("Tuple:", student)
# Access by index
print("Name:", student[0])
print("Age:", student[1])
print("Last:", student[-1])
# Slicing
print("Slice [1:3]:", student[1:3])
# Length
print("Length:", len(student))
# Iterating
for item in student:
 print(item)